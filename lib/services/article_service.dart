  List<Article> getArticles({String? level}) {
    if (level == null || level == 'All' || level == 'Бүх' || level == 'すべて') {
      return _articles;
    }
    return _articles.where((a) => a.level == level).toList();
  }

  Article getArticle(String id) =>
      _articles.firstWhere((a) => a.id == id, orElse: () => _articles.first);
}
